<script>
var allProphets = <?= json_encode($prophets, JSON_UNESCAPED_UNICODE) ?>;
var filteredProphets = allProphets;
var currentProphetCat = 'all';
var prophetPage = 1;
var prophetPageSize = 6;
var prophetModalInstance = null;

function filterProphets(cat, btn) {
    document.querySelectorAll('.filter-prophet').forEach(function(b) {
        b.className = 'btn btn-outline-primary rounded-pill px-4 filter-prophet';
    });
    btn.className = 'btn btn-primary rounded-pill px-4 filter-prophet active';
    currentProphetCat = cat;
    applyProphetFilters();
}

function applyProphetFilters() {
    var q = document.getElementById('prophetSearch').value.trim().toLowerCase();
    filteredProphets = allProphets.filter(function(p) {
        var matchCat = currentProphetCat === 'all' || p.category === currentProphetCat;
        var matchQ   = p.name.includes(q) || p.title.includes(q) || p.desc.includes(q);
        return matchCat && matchQ;
    });

    prophetPage = 1;
    renderProphets();
}

function renderProphets() {
    var grid = document.getElementById('prophetsGrid');
    var noRes = document.getElementById('noProphetResults');
    var pag = document.getElementById('prophetPagination');
    grid.innerHTML = '';

    if (filteredProphets.length === 0) {
        noRes.classList.remove('d-none');
        pag.style.display = 'none';
        return;
    }
    noRes.classList.add('d-none');

    var totalPages = Math.ceil(filteredProphets.length / prophetPageSize);
    var start = (prophetPage - 1) * prophetPageSize;
    var end = Math.min(start + prophetPageSize, filteredProphets.length);
    var pageItems = filteredProphets.slice(start, end);

    pageItems.forEach(function(p) {
        var col = document.createElement('div');
        col.className = 'col-lg-4 col-md-6';
        col.innerHTML = 
            '<div class="card h-100 border-0 shadow-sm rounded-4 overflow-hidden d-flex flex-column">' +
                '<img src="' + p.image + '" class="card-img-top" alt="' + p.name + '" style="height: 180px; object-fit: cover; filter: brightness(0.85);">' +
                '<div class="card-body p-4 d-flex flex-column justify-content-between flex-grow-1">' +
                    '<div>' +
                        '<div class="d-flex justify-content-between align-items-center mb-2">' +
                            '<h4 class="fw-bold text-primary mb-0">' + p.name + '</h4>' +
                            '<span class="badge bg-light text-muted px-3 py-1 rounded-pill">' + p.category + '</span>' +
                        '</div>' +
                        '<h6 class="text-muted mb-3">' + p.title + '</h6>' +
                        '<p class="text-secondary small mb-4">' + p.desc + '</p>' +
                    '</div>' +
                    '<button type="button" class="btn btn-outline-primary rounded-pill w-100 fw-bold" onclick="showProphetModal(`' + escapeQuotes(p.name) + '`, `' + escapeQuotes(p.title) + '`, `' + escapeQuotes(p.full_story) + '`)">' +
                        '<i data-lucide="book-open" style="width:14px;height:14px;" class="me-1"></i> اقرأ القصة كاملة' +
                    '</button>' +
                '</div>' +
            '</div>';
        grid.appendChild(col);
    });

    if (totalPages > 1) {
        pag.style.display = 'flex';
        document.getElementById('prophetPageIndicator').textContent = 'صفحة ' + prophetPage + ' من ' + totalPages;
        document.getElementById('prevProphetBtn').disabled = prophetPage <= 1;
        document.getElementById('nextProphetBtn').disabled = prophetPage >= totalPages;
    } else {
        pag.style.display = 'none';
    }

    if (typeof lucide !== 'undefined') lucide.createIcons();
}

function changeProphetPage(delta) {
    prophetPage += delta;
    renderProphets();
    window.scrollTo({ top: 350, behavior: 'smooth' });
}

function showProphetModal(name, title, story) {
    document.getElementById('modalProphetName').textContent = name;
    document.getElementById('modalProphetSubtitle').textContent = title;
    document.getElementById('modalProphetStory').innerHTML = story;
    if (!prophetModalInstance) prophetModalInstance = new bootstrap.Modal(document.getElementById('prophetModal'));
    prophetModalInstance.show();
}

function escapeQuotes(str) {
    if (!str) return '';
    return str.replace(/`/g, "'").replace(/"/g, '&quot;');
}

document.getElementById('prophetSearch').addEventListener('input', applyProphetFilters);

document.addEventListener('DOMContentLoaded', function() {
    renderProphets();
});
</script>
