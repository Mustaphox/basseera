<script>
var allSahaba = <?= json_encode($sahaba, JSON_UNESCAPED_UNICODE) ?>;
var filteredSahaba = allSahaba;
var currentSahabaCat = 'all';
var sahabaPage = 1;
var sahabaPageSize = 6;
var sahabaModalInstance = null;

function filterSahaba(cat, btn) {
    document.querySelectorAll('.filter-sahaba').forEach(function(b) {
        b.className = 'btn btn-outline-primary rounded-pill px-4 filter-sahaba';
    });
    btn.className = 'btn btn-primary rounded-pill px-4 filter-sahaba active';
    currentSahabaCat = cat;
    applySahabaFilters();
}

function applySahabaFilters() {
    var q = document.getElementById('sahabaSearch').value.trim().toLowerCase();
    filteredSahaba = allSahaba.filter(function(s) {
        var matchCat = currentSahabaCat === 'all' || s.category === currentSahabaCat;
        var matchQ   = s.name.includes(q) || s.title.includes(q) || s.desc.includes(q);
        return matchCat && matchQ;
    });

    sahabaPage = 1;
    renderSahaba();
}

function renderSahaba() {
    var grid = document.getElementById('sahabaGrid');
    var noRes = document.getElementById('noSahabaResults');
    var pag = document.getElementById('sahabaPagination');
    grid.innerHTML = '';

    if (filteredSahaba.length === 0) {
        noRes.classList.remove('d-none');
        pag.style.display = 'none';
        return;
    }
    noRes.classList.add('d-none');

    var totalPages = Math.ceil(filteredSahaba.length / sahabaPageSize);
    var start = (sahabaPage - 1) * sahabaPageSize;
    var end = Math.min(start + sahabaPageSize, filteredSahaba.length);
    var pageItems = filteredSahaba.slice(start, end);

    pageItems.forEach(function(s) {
        var col = document.createElement('div');
        col.className = 'col-lg-4 col-md-6';
        col.innerHTML = 
            '<div class="card h-100 border-0 shadow-sm rounded-4 text-center p-4 d-flex flex-column justify-content-between">' +
                '<div>' +
                    '<div class="bg-light-primary text-primary mx-auto rounded-circle d-flex align-items-center justify-content-center mb-3" style="width: 70px; height: 70px;">' +
                        '<i data-lucide="user" width="34" height="34"></i>' +
                    '</div>' +
                    '<h4 class="fw-bold mb-1 text-primary">' + s.name + '</h4>' +
                    '<span class="badge bg-light text-muted px-3 py-1 rounded-pill mb-3">' + s.category + '</span>' +
                    '<h6 class="text-secondary mb-3 small">' + s.title + '</h6>' +
                    '<p class="text-muted small mb-4">' + s.desc + '</p>' +
                '</div>' +
                '<button class="btn btn-outline-primary rounded-pill w-100 fw-bold" onclick="showSahabaModal(`' + escapeQuotes(s.name) + '`, `' + escapeQuotes(s.title) + '`, `' + escapeQuotes(s.full_story) + '`)">' +
                    '<i data-lucide="book-open" style="width:14px;height:14px;" class="me-1"></i> اقرأ سيرته' +
                '</button>' +
            '</div>';
        grid.appendChild(col);
    });

    if (totalPages > 1) {
        pag.style.display = 'flex';
        document.getElementById('sahabaPageIndicator').textContent = 'صفحة ' + sahabaPage + ' من ' + totalPages;
        document.getElementById('prevSahabaBtn').disabled = sahabaPage <= 1;
        document.getElementById('nextSahabaBtn').disabled = sahabaPage >= totalPages;
    } else {
        pag.style.display = 'none';
    }

    if (typeof lucide !== 'undefined') lucide.createIcons();
}

function changeSahabaPage(delta) {
    sahabaPage += delta;
    renderSahaba();
    window.scrollTo({ top: 350, behavior: 'smooth' });
}

function showSahabaModal(name, title, story) {
    document.getElementById('modalSahabaName').textContent = name;
    document.getElementById('modalSahabaTitle').textContent = title;
    document.getElementById('modalSahabaStory').innerHTML = story;
    if (!sahabaModalInstance) sahabaModalInstance = new bootstrap.Modal(document.getElementById('sahabaModal'));
    sahabaModalInstance.show();
}

function escapeQuotes(str) {
    if (!str) return '';
    return str.replace(/`/g, "'").replace(/"/g, '&quot;');
}

document.getElementById('sahabaSearch').addEventListener('input', applySahabaFilters);

document.addEventListener('DOMContentLoaded', function() {
    renderSahaba();
});
</script>
